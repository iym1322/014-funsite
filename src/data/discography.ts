export type TrackRef = { title: string; slug?: string };
export type SetlistGroup = { title: string; tracks: TrackRef[] };

export type Track = {
  title: string;
  group: "Sound Schedule" | "大石昌良" | "オーイシマサヨシ" | "OxT" | "楽曲提供";
  type: "アルバム" | "シングル" | "映像" | "提供曲";
  date: string; // 表示用(判明している精度のまま。例: "2014", "2014.08", "2014.08.27")
  sortDate: string; // 並べ替え用に YYYY-MM-DD へ正規化(不明な月日は 01 で補完)
  tieIn?: string; // タイアップ・補足情報
  subject?: string; // 提供曲の場合の提供先アーティスト・作品名
  role?: string; // 提供曲の場合の関与(作詞/作曲/編曲など)
  note?: string;
  caution?: boolean; // 出典間で表記が揺れる/裏取り不十分な項目
  youtube?: string;
  appleMusic?: string;
  spotify?: string;
  slug?: string; // 個別ページ(/works/[slug])を持つ曲にのみ設定
  image?: string; // public/images/works/ 配下のファイル名(自分で用意した画像のみ使用)
  description?: string; // 楽曲紹介文
  tracklist?: TrackRef[]; // アルバムの収録曲(判明分のみ。未調査なら省略=個別ページで「準備中」表示)
  isLive?: boolean; // 映像作品がライブ映像かどうか(true の場合のみセットリストを表示)
  setlist?: TrackRef[]; // ライブ映像のセットリスト(判明分のみ。未調査なら省略=個別ページで「準備中」表示)
  setlists?: SetlistGroup[]; // 複数公演を収録する映像作品の公演別セットリスト
};

const toSortDate = (date: string): string => {
  const parts = date.split(".");
  const y = parts[0]?.padEnd(4, "0") ?? "0000";
  const m = (parts[1] ?? "01").padStart(2, "0");
  const d = (parts[2] ?? "01").padStart(2, "0");
  return `${y}-${m}-${d}`;
};

